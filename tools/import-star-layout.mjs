#!/usr/bin/env node

// Imports one JSON document exported by ?author=layout into the sparse
// repository registry. The browser has already measured rendered geometry;
// this tool independently validates schema, puzzle revision, node identity,
// board bounds, and the exported hard metrics before writing anything.

import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { PUZZLES } from "../puzzles/index.js";
import { validateStarLayoutDocument } from "../modules/starLayoutSchema.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export async function importStarLayout(
  inputPath,
  { checkOnly = false, repositoryRoot = root } = {}
) {
  const raw = await readFile(inputPath, "utf8");
  const layout = JSON.parse(raw);
  const puzzle = PUZZLES.find(candidate => candidate.id === layout.puzzleId);
  if (!puzzle) throw new Error(`unknown puzzleId "${layout.puzzleId}"`);

  const validation = validateStarLayoutDocument(layout, puzzle);
  if (!validation.valid) {
    throw new Error(validation.errors.join("\n"));
  }
  if (checkOnly) return { layout, puzzle, outputPath: null };

  const layoutDirectory = join(repositoryRoot, "puzzles", "layouts", "star");
  await mkdir(layoutDirectory, { recursive: true });
  const outputPath = join(layoutDirectory, `${puzzle.id}.js`);
  const output = [
    "// Generated by tools/import-star-layout.mjs from the layout authoring export.",
    `export default ${JSON.stringify(layout, null, 2)};`,
    ""
  ].join("\n");
  await writeFile(outputPath, output, "utf8");

  const layoutFiles = (await readdir(layoutDirectory))
    .filter(name =>
      name.endsWith(".js") &&
      name !== "index.js" &&
      name !== "free-strip.js"
    )
    .sort();
  const imports = layoutFiles.map((name, index) =>
    `import layout${index} from "./${name}";`);
  const entries = layoutFiles.map((_, index) =>
    `  [layout${index}.puzzleId]: layout${index}`);
  const registry = [
    "// Optional, hand-authored final layouts for Star mode.",
    "// Generated by tools/import-star-layout.mjs; do not edit by hand.",
    ...imports,
    "",
    "export const STAR_LAYOUTS = {",
    entries.join(",\n"),
    "};",
    "",
    "export default STAR_LAYOUTS;",
    ""
  ].join("\n");
  await writeFile(join(layoutDirectory, "index.js"), registry, "utf8");

  return { layout, puzzle, outputPath, repositoryRoot };
}

async function main() {
  const args = process.argv.slice(2);
  const checkOnly = args.includes("--check");
  const input = args.find(arg => arg !== "--check");
  if (!input) {
    console.error("Usage: node tools/import-star-layout.mjs <layout.json> [--check]");
    process.exitCode = 1;
    return;
  }
  try {
    const result = await importStarLayout(input, { checkOnly });
    console.log(checkOnly
      ? `VALID ${result.puzzle.id}`
      : `IMPORTED ${result.puzzle.id} -> ${relative(result.repositoryRoot, result.outputPath)}`);
  } catch (error) {
    console.error(`INVALID LAYOUT\n${error.message}`);
    process.exitCode = 1;
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main();
}

#!/usr/bin/env node

// Imports a tiny JSON flag exported from &admin ("Export strip flag") into
// the sparse STAR_FREE_STRIP registry. freeStrip: false removes the entry.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { PUZZLES } from "../puzzles/index.js";
import { STAR_FREE_STRIP } from "../puzzles/layouts/star/free-strip.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export async function importStarFreeStrip(
  inputPath,
  { checkOnly = false, repositoryRoot = root, registry = STAR_FREE_STRIP } = {}
) {
  const raw = await readFile(inputPath, "utf8");
  const doc = JSON.parse(raw);
  if (doc.kind !== "star-free-strip") {
    throw new Error(`expected kind "star-free-strip", got ${JSON.stringify(doc.kind)}`);
  }
  if (doc.schemaVersion !== 1) {
    throw new Error(`unsupported schemaVersion ${doc.schemaVersion}`);
  }
  const puzzle = PUZZLES.find(candidate => candidate.id === doc.puzzleId);
  if (!puzzle) throw new Error(`unknown puzzleId "${doc.puzzleId}"`);
  if (typeof doc.freeStrip !== "boolean") {
    throw new Error("freeStrip must be a boolean");
  }
  if (checkOnly) return { doc, puzzle, outputPath: null };

  const current = { ...registry };
  if (doc.freeStrip) current[doc.puzzleId] = true;
  else delete current[doc.puzzleId];

  const ids = Object.keys(current).sort();
  const body = ids.length
    ? ids.map(id => `  ${JSON.stringify(id)}: true`).join(",\n")
    : "";
  const output = [
    "// Sparse per-puzzle flag: Star cold-start uses Circle-style free-term",
    "// strip packing when true. Default is false (classic force board). Locked",
    "// from &admin after a cluttered opening; import with",
    "// `node tools/import-star-free-strip.mjs <file>`.",
    "// Generated by tools/import-star-free-strip.mjs; do not edit by hand.",
    "export const STAR_FREE_STRIP = {",
    body,
    "};",
    "",
    "export default STAR_FREE_STRIP;",
    ""
  ].join("\n");
  const outputPath = join(repositoryRoot, "puzzles", "layouts", "star", "free-strip.js");
  await writeFile(outputPath, output, "utf8");
  return { doc, puzzle, outputPath, repositoryRoot };
}

async function main() {
  const args = process.argv.slice(2);
  const checkOnly = args.includes("--check");
  const input = args.find(arg => arg !== "--check");
  if (!input) {
    console.error("Usage: node tools/import-star-free-strip.mjs <flag.json> [--check]");
    process.exitCode = 1;
    return;
  }
  try {
    const result = await importStarFreeStrip(input, { checkOnly });
    console.log(checkOnly
      ? `VALID ${result.doc.puzzleId} freeStrip=${result.doc.freeStrip}`
      : `${result.doc.freeStrip ? "LOCKED" : "CLEARED"} ${result.doc.puzzleId} -> ${relative(result.repositoryRoot, result.outputPath)}`);
  } catch (error) {
    console.error(`INVALID FLAG\n${error.message}`);
    process.exitCode = 1;
  }
}

// pathToFileURL handles relative argv[1] (fileURLToPath equality alone can
// miss that case on some Node/platform combinations).
const isCli = process.argv[1] &&
  pathToFileURL(process.argv[1]).href === import.meta.url;
if (isCli) {
  await main();
}

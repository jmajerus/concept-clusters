#!/usr/bin/env node
// Build puzzles/manifest.js from puzzles/index.js — browse metadata for the
// player plus module paths for lazy import(). Skips modules that fail to load
// so a broken puzzle does not block manifest generation.

import { execFile } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { promisify } from "node:util";
import { puzzleBrowseFromFull } from "../modules/puzzleBrowse.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const INDEX_PATH = join(ROOT, "puzzles", "index.js");
const MANIFEST_PATH = join(ROOT, "puzzles", "manifest.js");

function parseImportMap(source) {
  const map = new Map();
  for (const match of source.matchAll(/^import (\w+) from "(\.\/[^"]+)";/gm)) {
    map.set(match[1], match[2]);
  }
  return map;
}

function parseWrapperSources(source) {
  const map = new Map();
  for (const match of source.matchAll(/^const (\w+) = \{\s*\.\.\.(\w+)/gm)) {
    map.set(match[1], match[2]);
  }
  return map;
}

function parsePuzzleVariables(source) {
  const block = source.match(/export const PUZZLES = \[([\s\S]*?)\n\];/);
  if (!block) throw new Error("Could not locate PUZZLES array in puzzles/index.js");
  return [...block[1].matchAll(/^\s+(\w+),?$/gm)].map(match => match[1]);
}

function registryPatch(sourcePuzzle, registryPuzzle) {
  const patch = {};
  for (const key of ["category", "categories", "subcategories"]) {
    const registryValue = registryPuzzle[key];
    const sourceValue = sourcePuzzle[key];
    if (JSON.stringify(registryValue) !== JSON.stringify(sourceValue)) {
      patch[key] = registryValue;
    }
  }
  return Object.keys(patch).length ? patch : undefined;
}

const execFileAsync = promisify(execFile);

async function git(repositoryRoot, args) {
  const { stdout } = await execFileAsync("git", ["-C", repositoryRoot, ...args], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024
  });
  return stdout;
}

// Dates already stamped in the committed manifest. The manifest is the
// ledger for `published`: rebuilds that cannot see history (a shallow CI
// checkout, canonicalize-content's tmpdir overlay) must not blank or move a
// date that a full-history build already wrote.
async function existingPublishedDates(manifestPath) {
  const dates = new Map();
  let mod;
  try {
    mod = await import(`${pathToFileURL(manifestPath).href}?t=${Date.now()}`);
  } catch {
    return dates;
  }
  for (const entry of mod.PUZZLE_MANIFEST || []) {
    if (entry?.id && /^\d{4}-\d{2}-\d{2}$/.test(entry.published || "")) {
      dates.set(entry.id, entry.published);
    }
  }
  return dates;
}

// First-added date per file stem (path minus directory and extensions) from
// one `git log` pass, or null when the checkout has no usable history (not
// a repository, or a shallow clone whose "first add" would just be its
// truncation point). Stems rather than paths: category moves and the
// .jsonld -> .ccpuzzle.json rename would otherwise look like fresh adds.
async function gitFirstAddedDates(repositoryRoot) {
  try {
    const shallow = (await git(repositoryRoot, ["rev-parse", "--is-shallow-repository"])).trim();
    if (shallow !== "false") return null;
    const log = await git(repositoryRoot, [
      "log", "--diff-filter=A", "--name-only", "--format=%as", "--",
      "puzzles", "content/puzzles"
    ]);
    const dates = new Map();
    let current = null;
    for (const line of log.split("\n")) {
      if (/^\d{4}-\d{2}-\d{2}$/.test(line)) {
        current = line;
      } else if (line && current) {
        const stem = line.slice(line.lastIndexOf("/") + 1).split(".")[0];
        const prior = dates.get(stem);
        if (!prior || current < prior) dates.set(stem, current);
      }
    }
    return dates;
  } catch {
    return null;
  }
}

// First-published date for the player's About card: the earliest add of any
// file named after the puzzle id under puzzles/ or content/puzzles/. The
// first 20 boards lived in a single puzzles.js before the 2026-07-23 split,
// so they read a few days late -- month granularity in the UI absorbs that.
function firstPublished(id, gitDates) {
  return gitDates?.get(id) || undefined;
}

export function serializeManifest(entries, failures) {
  const body = JSON.stringify(entries, null, 2);
  return `// Generated by tools/build-puzzle-manifest.mjs — do not edit by hand.
// Rebuild after puzzles/index.js changes: npm run puzzles:build-manifest

export const PUZZLE_MANIFEST = ${body};

export const PUZZLE_MANIFEST_FAILURES = ${JSON.stringify(failures, null, 2)};
`;
}

export async function buildPuzzleManifest({
  repositoryRoot = ROOT,
  write = true
} = {}) {
  const indexPath = join(repositoryRoot, "puzzles", "index.js");
  const manifestPath = join(repositoryRoot, "puzzles", "manifest.js");
  const source = await readFile(indexPath, "utf8");
  const importMap = parseImportMap(source);
  const wrapperSources = parseWrapperSources(source);
  const puzzleVariables = parsePuzzleVariables(source);

  const { PUZZLES } = await import(pathToFileURL(indexPath).href);
  const stampedDates = await existingPublishedDates(manifestPath);
  const gitDates = await gitFirstAddedDates(repositoryRoot);
  const entries = [];
  const failures = [];

  for (let index = 0; index < puzzleVariables.length; index += 1) {
    const varName = puzzleVariables[index];
    const registryPuzzle = PUZZLES[index];
    const sourceVar = wrapperSources.get(varName) || varName;
    const moduleRel = importMap.get(sourceVar);
    if (!moduleRel) {
      failures.push({
        id: registryPuzzle?.id || varName,
        module: null,
        error: `No import for registry variable "${varName}"`
      });
      continue;
    }
    if (!registryPuzzle?.id) {
      failures.push({ id: varName, module: moduleRel, error: "Registry entry missing id" });
      continue;
    }

    let patch;
    try {
      const modulePath = join(repositoryRoot, "puzzles", moduleRel.replace(/^\.\//, ""));
      const mod = await import(pathToFileURL(modulePath).href);
      const sourcePuzzle = mod.default;
      if (!sourcePuzzle?.id) {
        throw new Error("module default export missing id");
      }
      if (wrapperSources.has(varName)) {
        patch = registryPatch(sourcePuzzle, registryPuzzle);
      }
    } catch (error) {
      failures.push({
        id: registryPuzzle.id,
        module: moduleRel,
        error: error instanceof Error ? error.message : String(error)
      });
      continue;
    }

    const published = stampedDates.get(registryPuzzle.id)
      || firstPublished(registryPuzzle.id, gitDates);
    entries.push({
      id: registryPuzzle.id,
      module: moduleRel,
      ...(patch ? { patch } : {}),
      ...(published ? { published } : {}),
      browse: puzzleBrowseFromFull(registryPuzzle)
    });
  }

  const output = serializeManifest(entries, failures);
  if (write) {
    await writeFile(manifestPath, output, "utf8");
  }
  // Returning the serialized bytes lets migration planners compare the
  // rebuilt artifact without mutating the working tree.  Existing callers
  // still receive the original entries/failures/path fields unchanged.
  return { entries, failures, manifestPath, content: output };
}

const isCli = process.argv[1] &&
  pathToFileURL(process.argv[1]).href === import.meta.url;

if (isCli) {
  const result = await buildPuzzleManifest();
  if (result.failures.length) {
    console.warn(
      `Skipped ${result.failures.length} puzzle(s) while building manifest:`
    );
    for (const failure of result.failures) {
      console.warn(`  - ${failure.id}: ${failure.error}`);
    }
  }
  console.log(
    `Wrote ${result.entries.length} manifest entries to ${result.manifestPath}`
  );
}

#!/usr/bin/env node

// Imports a tiny JSON flag exported from &admin ("Export bridge pre-connect
// flag") into the sparse STAR_BRIDGE_PRECONNECT registry.
// preconnect: false removes the entry.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { PUZZLES } from "../puzzles/index.js";
import { STAR_BRIDGE_PRECONNECT } from "../puzzles/layouts/star/bridge-preconnect.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export async function importStarBridgePreconnect(
  inputPath,
  { checkOnly = false, repositoryRoot = root, registry = STAR_BRIDGE_PRECONNECT } = {}
) {
  const raw = await readFile(inputPath, "utf8");
  const doc = JSON.parse(raw);
  if (doc.kind !== "star-bridge-preconnect") {
    throw new Error(`expected kind "star-bridge-preconnect", got ${JSON.stringify(doc.kind)}`);
  }
  if (doc.schemaVersion !== 1) {
    throw new Error(`unsupported schemaVersion ${doc.schemaVersion}`);
  }
  const puzzle = PUZZLES.find(candidate => candidate.id === doc.puzzleId);
  if (!puzzle) throw new Error(`unknown puzzleId "${doc.puzzleId}"`);
  if (typeof doc.preconnect !== "boolean") {
    throw new Error("preconnect must be a boolean");
  }
  if (checkOnly) return { doc, puzzle, outputPath: null };

  const current = { ...registry };
  if (doc.preconnect) current[doc.puzzleId] = true;
  else delete current[doc.puzzleId];

  const ids = Object.keys(current).sort();
  const body = ids.length
    ? ids.map(id => `  ${JSON.stringify(id)}: true`).join(",\n")
    : "";
  const output = [
    "// Sparse per-puzzle flag: cold start pre-connects every bridge in Graph,",
    "// Star, and Circle when true. Default is false. Locked from &admin; import with",
    "// `node tools/import-star-bridge-preconnect.mjs <file>`.",
    "// Generated by tools/import-star-bridge-preconnect.mjs; do not edit by hand.",
    "export const STAR_BRIDGE_PRECONNECT = {",
    body,
    "};",
    "",
    "export default STAR_BRIDGE_PRECONNECT;",
    ""
  ].join("\n");
  const outputPath = join(repositoryRoot, "puzzles", "layouts", "star", "bridge-preconnect.js");
  await writeFile(outputPath, output, "utf8");
  return { doc, puzzle, outputPath, repositoryRoot };
}

async function main() {
  const args = process.argv.slice(2);
  const checkOnly = args.includes("--check");
  const input = args.find(arg => arg !== "--check");
  if (!input) {
    console.error("Usage: node tools/import-star-bridge-preconnect.mjs <flag.json> [--check]");
    process.exitCode = 1;
    return;
  }
  try {
    const result = await importStarBridgePreconnect(input, { checkOnly });
    console.log(checkOnly
      ? `VALID ${result.doc.puzzleId} preconnect=${result.doc.preconnect}`
      : `${result.doc.preconnect ? "LOCKED" : "CLEARED"} ${result.doc.puzzleId} -> ${relative(result.repositoryRoot, result.outputPath)}`);
  } catch (error) {
    console.error(`INVALID FLAG\n${error.message}`);
    process.exitCode = 1;
  }
}

const isCli = process.argv[1] &&
  pathToFileURL(process.argv[1]).href === import.meta.url;
if (isCli) {
  await main();
}

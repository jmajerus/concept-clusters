// Writes puzzles/domains.js, the git snapshot of the published domains, as
// Freeze does for puzzles/categories.js. The public site's static fallback,
// CI, and validate.mjs read the snapshot; everything live reads the rows.

import { GENERATED_DOMAIN_IDS } from "../puzzles/domains.js";

const HEADER = `// Generated by Freeze from the published domain documents
// (modules/domainsSnapshot.js). Domains are added and renamed in
// terminology-mcp's cc-subjects scheme, not here.
// Domains are the top level of the subject taxonomy: category records name
// one by id. The category browse screen sorts them by title, so the order
// here carries no meaning. See docs/TAXONOMY-ROADMAP.md.
`;

export function renderDomainsSource(domains) {
  const sorted = Object.fromEntries(
    Object.entries(domains).sort(([, left], [, right]) => left.title.localeCompare(right.title))
  );
  return `${HEADER}export const DOMAINS = ${JSON.stringify(sorted, null, 2)};

export const GENERATED_DOMAIN_IDS = Object.freeze(${JSON.stringify(GENERATED_DOMAIN_IDS, null, 2)});

export const RESERVED_DOMAIN_IDS = new Set(
  Object.values(GENERATED_DOMAIN_IDS)
);
`;
}

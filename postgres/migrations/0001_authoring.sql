-- Authoring working copies. Published player rows stay in D1.
-- JSON is text and is parsed in JavaScript. Timestamps are ISO text.

CREATE TABLE IF NOT EXISTS puzzle_drafts (
  id TEXT PRIMARY KEY,
  puzzle_id TEXT,
  owner_subject TEXT NOT NULL,
  title TEXT,
  status TEXT NOT NULL CHECK (
    status IN ('draft', 'review', 'submitted', 'published', 'archived')
  ),
  document TEXT NOT NULL,
  content_hash TEXT NOT NULL,
  validation_json TEXT,
  base_commit_sha TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  revision INTEGER NOT NULL DEFAULT 1 CHECK (revision >= 1),
  installed_content_hash TEXT,
  content_json TEXT,
  pedagogy_json TEXT,
  provenance_json TEXT,
  classification_json TEXT,
  administration_json TEXT,
  layout_json TEXT,
  document_stale INTEGER NOT NULL DEFAULT 0,
  opened_from_published INTEGER NOT NULL DEFAULT 0,
  review_baseline_json TEXT,
  review_base_published_revision INTEGER
);

CREATE INDEX IF NOT EXISTS puzzle_drafts_owner_updated
  ON puzzle_drafts(owner_subject, updated_at DESC);
CREATE INDEX IF NOT EXISTS puzzle_drafts_owner_status_updated
  ON puzzle_drafts(owner_subject, status, updated_at DESC);

CREATE TABLE IF NOT EXISTS puzzle_draft_history (
  draft_id TEXT NOT NULL REFERENCES puzzle_drafts(id) ON DELETE CASCADE,
  seq INTEGER NOT NULL CHECK (seq >= 1),
  document TEXT,
  content_json TEXT,
  pedagogy_json TEXT,
  classification_json TEXT,
  provenance_json TEXT,
  administration_json TEXT,
  content_hash TEXT NOT NULL,
  saved_at TEXT NOT NULL,
  PRIMARY KEY (draft_id, seq)
);

CREATE INDEX IF NOT EXISTS puzzle_draft_history_draft_seq
  ON puzzle_draft_history(draft_id, seq DESC);

CREATE TABLE IF NOT EXISTS draft_assistance_stamps (
  id TEXT PRIMARY KEY,
  draft_id TEXT NOT NULL,
  owner_subject TEXT NOT NULL,
  captured_at TEXT NOT NULL,
  record_json TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS draft_assistance_stamps_draft_captured
  ON draft_assistance_stamps(draft_id, captured_at DESC);
CREATE INDEX IF NOT EXISTS draft_assistance_stamps_owner_captured
  ON draft_assistance_stamps(owner_subject, captured_at DESC);

CREATE TABLE IF NOT EXISTS content_drafts (
  kind TEXT NOT NULL CHECK (kind IN ('catalogue', 'category')),
  id TEXT NOT NULL,
  owner_subject TEXT NOT NULL,
  title TEXT,
  document TEXT NOT NULL,
  content_hash TEXT NOT NULL,
  revision INTEGER NOT NULL CHECK (revision >= 1),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY (kind, id, owner_subject)
);

CREATE INDEX IF NOT EXISTS content_drafts_owner_updated
  ON content_drafts(owner_subject, kind, updated_at DESC);

CREATE TABLE IF NOT EXISTS puzzle_board_limit_waiver_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draft_id TEXT NOT NULL,
  puzzle_id TEXT NOT NULL,
  waiver_type TEXT NOT NULL,
  target_id TEXT NOT NULL,
  requested_count INTEGER NOT NULL,
  reason TEXT NOT NULL,
  status TEXT NOT NULL CHECK (
    status IN ('pending', 'granted', 'declined', 'superseded', 'replaced', 'revoked')
  ),
  requested_by TEXT NOT NULL,
  requested_at TEXT NOT NULL,
  requested_revision INTEGER NOT NULL,
  decided_by TEXT,
  decided_at TEXT,
  decision_note TEXT
);

CREATE INDEX IF NOT EXISTS board_limit_waiver_requests_by_draft
  ON puzzle_board_limit_waiver_requests(draft_id, status, requested_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS board_limit_waiver_one_pending_per_scope
  ON puzzle_board_limit_waiver_requests(draft_id, waiver_type, target_id, requested_count)
  WHERE status = 'pending';

CREATE TABLE IF NOT EXISTS puzzle_board_limit_waiver_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  puzzle_id TEXT NOT NULL,
  waiver_type TEXT NOT NULL,
  target_id TEXT NOT NULL,
  event_type TEXT NOT NULL CHECK (event_type IN ('granted', 'replaced', 'revoked')),
  actor TEXT NOT NULL,
  event_at TEXT NOT NULL,
  approved_count INTEGER NOT NULL,
  reason TEXT,
  draft_id TEXT,
  draft_revision INTEGER
);

CREATE INDEX IF NOT EXISTS board_limit_waiver_events_by_puzzle
  ON puzzle_board_limit_waiver_events(puzzle_id, waiver_type, target_id, event_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS puzzle_review_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  puzzle_id TEXT NOT NULL,
  reviewer_kind TEXT NOT NULL CHECK (reviewer_kind IN ('agent', 'human')),
  reviewed_at TEXT NOT NULL,
  comments TEXT,
  outcome TEXT,
  draft_revision INTEGER,
  guidance_major INTEGER,
  guidance_minor INTEGER,
  issue_id TEXT,
  event_type TEXT NOT NULL DEFAULT 'review',
  proposal_json TEXT,
  base_published_revision INTEGER,
  published_revision INTEGER,
  client_system TEXT,
  client_model TEXT,
  client_name TEXT,
  source_event_id INTEGER
);

CREATE INDEX IF NOT EXISTS puzzle_review_events_by_puzzle_and_date
  ON puzzle_review_events(puzzle_id, reviewed_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS puzzle_review_events_by_puzzle_issue_and_date
  ON puzzle_review_events(puzzle_id, issue_id, reviewed_at ASC, id ASC);

CREATE TABLE IF NOT EXISTS authoring_model_suggestions (
  label TEXT PRIMARY KEY,
  created_by TEXT,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS wiki_link_checks (
  title TEXT PRIMARY KEY,
  page_exists INTEGER NOT NULL CHECK (page_exists IN (0, 1)),
  disambiguation INTEGER NOT NULL DEFAULT 0 CHECK (disambiguation IN (0, 1)),
  resolved_title TEXT,
  checked_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS wiki_link_checks_checked_at ON wiki_link_checks(checked_at);

CREATE TABLE IF NOT EXISTS site_settings (
  key TEXT PRIMARY KEY,
  value_json TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  updated_by TEXT
);

CREATE TABLE IF NOT EXISTS freeze_requests (
  id TEXT PRIMARY KEY,
  status TEXT NOT NULL,
  plan_hash TEXT NOT NULL,
  plan_json TEXT NOT NULL,
  github_branch TEXT NOT NULL,
  github_commit_sha TEXT,
  github_pr_number INTEGER,
  github_pr_url TEXT,
  summary TEXT NOT NULL,
  additional_context TEXT,
  error_message TEXT,
  requested_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  reconciled_at TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS freeze_requests_one_active
  ON freeze_requests(status)
  WHERE status IN ('requested', 'pull-request-open');
